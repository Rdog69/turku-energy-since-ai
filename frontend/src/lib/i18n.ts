const DICTS: Record<Lang, Dict> = { en, fi };

export function t(lang: Lang, key: string, vars: Record<string, string | number> = {}): string {
  const s = DICTS[lang][key] ?? DICTS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}

